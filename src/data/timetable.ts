/** Free study windows after the last class of each day, for the given lab group. */
export function freeAfter(group: 1 | 2): Record<string, string> {
  const byDay: Record<string, string> = {};
  for (const s of slots) {
    if (s.group !== null && s.group !== group) continue;
    if (!byDay[s.day] || s.end > byDay[s.day]) byDay[s.day] = s.end;
  }
  return byDay;
}
